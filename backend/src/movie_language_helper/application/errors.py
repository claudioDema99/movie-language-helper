"""Stable application errors independent of HTTP and providers."""


class ApplicationError(RuntimeError):
    """A safe error mapped by inbound adapters."""

    def __init__(
        self,
        code: str,
        message: str,
        *,
        retryable: bool = False,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.retryable = retryable
